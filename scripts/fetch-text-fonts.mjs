/**
 * Developer tool (NOT part of the build, needs network): downloads the fonts the text engine bundles into
 * resources/textfonts, pinned to exact upstream commits, so the font set is reproducible.
 *
 *   node scripts/fetch-text-fonts.mjs          # downloads what is missing
 *   node scripts/fetch-text-fonts.mjs --force  # re-downloads everything
 *
 * Afterwards run `node scripts/build-text-manifest.mjs` to regenerate resources/textfonts/text-fonts.json and the
 * license notice. The fonts are committed; the app never downloads anything.
 *
 * Sources (all SIL Open Font License 1.1):
 *   - https://github.com/notofonts/notofonts.github.io   (Noto scripts, "unhinted" TTF builds: smaller, and
 *                                                         the PDF subsetter drops hinting anyway)
 *   - https://github.com/notofonts/noto-cjk              (Noto Sans CJK "SubsetOTF": the regional subsets)
 *   - https://github.com/google/fonts (ofl/notoemoji)    (Noto Emoji, monochrome; variable font pinned to wght=400)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { subsetRaw } from './lib/hbSubsetRaw.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'resources', 'textfonts')
const force = process.argv.includes('--force')

const NOTO_SHA = 'f145d86c53996717bc4c25d4602eb9294e43dccc'
const CJK_SHA = 'f8d157532fbfaeda587e826d4cd5b21a49186f7c'
const GF_SHA = '23e54b51ddffbc7713c583748e3bd86f62b1fa4a'
const noto = (family, style) => `https://raw.githubusercontent.com/notofonts/notofonts.github.io/${NOTO_SHA}/fonts/${family}/unhinted/ttf/${family}-${style}.ttf`

/** [family, styles] */
const scripts = [
  ['NotoSansArabic', ['Regular', 'Bold']],
  ['NotoNaskhArabic', ['Regular', 'Bold']],
  ['NotoNastaliqUrdu', ['Regular', 'Bold']],
  ['NotoSansHebrew', ['Regular', 'Bold']],
  ['NotoSansThai', ['Regular', 'Bold']],
  ['NotoSansDevanagari', ['Regular', 'Bold']],
  ['NotoSansBengali', ['Regular', 'Bold']],
  ['NotoSansTamil', ['Regular', 'Bold']],
  ['NotoSansTelugu', ['Regular', 'Bold']],
  ['NotoSansGujarati', ['Regular', 'Bold']],
  ['NotoSansGurmukhi', ['Regular', 'Bold']],
  ['NotoSansKannada', ['Regular', 'Bold']],
  ['NotoSansMalayalam', ['Regular', 'Bold']],
  ['NotoSansOriya', ['Regular']],
  ['NotoSansSinhala', ['Regular']],
  ['NotoSansThaana', ['Regular']],
  ['NotoSansSyriac', ['Regular']],
  ['NotoSansArmenian', ['Regular']],
  ['NotoSansGeorgian', ['Regular']],
  ['NotoSansLao', ['Regular']],
  ['NotoSansKhmer', ['Regular']],
  ['NotoSansMyanmar', ['Regular']],
  ['NotoSansEthiopic', ['Regular']],
  ['NotoSansSymbols', ['Regular']],
  ['NotoSansSymbols2', ['Regular']],
  ['NotoSansMath', ['Regular']]
]

const downloads = []
for (const [family, styles] of scripts) for (const s of styles) downloads.push({ file: `${family}-${s}.ttf`, url: noto(family, s) })
for (const [code, name] of [['SC', 'SC'], ['TC', 'TC'], ['JP', 'JP'], ['KR', 'KR']]) {
  downloads.push({ file: `NotoSans${name}-Regular.otf`, url: `https://raw.githubusercontent.com/notofonts/noto-cjk/${CJK_SHA}/Sans/SubsetOTF/${code}/NotoSans${name}-Regular.otf` })
}

mkdirSync(outDir, { recursive: true })
async function get(url) {
  const r = await fetch(url)
  if (!r.ok) throw new Error(`${r.status} ${url}`)
  return new Uint8Array(await r.arrayBuffer())
}

for (const d of downloads) {
  const dest = join(outDir, d.file)
  if (existsSync(dest) && !force) continue
  const bytes = await get(d.url)
  writeFileSync(dest, bytes)
  console.log('downloaded', d.file, bytes.length)
}

// Noto Emoji (monochrome outlines): the upstream file is a variable font; pin the weight axis to its default so
// the bundled file is a plain static font that every PDF reader can use.
const emojiDest = join(outDir, 'NotoEmoji-Regular.ttf')
if (!existsSync(emojiDest) || force) {
  const vf = await get(`https://raw.githubusercontent.com/google/fonts/${GF_SHA}/ofl/notoemoji/NotoEmoji%5Bwght%5D.ttf`)
  const wasm = readFileSync(join(root, 'resources', 'text', 'harfbuzz-subset.wasm'))
  const out = await subsetRaw(wasm, vf, { keepEverything: true, pinAxesToDefault: true, noHinting: true })
  writeFileSync(emojiDest, out)
  console.log('built NotoEmoji-Regular.ttf (static, wght=400)', out.length)
}

// License texts: the OFL 1.1 text ships once; per-font copyright notices are generated by build-text-manifest.mjs.
const oflDest = join(outDir, 'OFL-1.1.txt')
if (!existsSync(oflDest) || force) {
  const t = await get(`https://raw.githubusercontent.com/notofonts/notofonts.github.io/${NOTO_SHA}/LICENSE`)
  writeFileSync(oflDest, t)
  console.log('downloaded OFL-1.1.txt')
}
